fun Int.toNumberText() = when {
    this < 10 -> "#00$this"
    this < 100 -> "#0$this"
    else -> "#$this"
}

@Composable
fun pokemonTypeColor(type: String): Color {
    val typeColors = AppTheme.colors.extraColors.type

    return when (type.trim().lowercase()) {
        "normal" -> typeColors.normal
        "feuer" -> typeColors.fire
        "wasser" -> typeColors.water
        "elektro" -> typeColors.electric
        "pflanze" -> typeColors.grass
        "eis" -> typeColors.ice
        "kampf" -> typeColors.fighting
        "gift" -> typeColors.poison
        "boden" -> typeColors.ground
        "flug" -> typeColors.flying
        "psycho" -> typeColors.psychic
        "käfer", "kaefer" -> typeColors.bug
        "gestein" -> typeColors.rock
        "geist" -> typeColors.ghost
        "drache" -> typeColors.dragon
        "unlicht" -> typeColors.dark
        "stahl" -> typeColors.steel
        "fee" -> typeColors.fairy
        else -> AppTheme.colors.material.onSurfaceVariant
    }
}